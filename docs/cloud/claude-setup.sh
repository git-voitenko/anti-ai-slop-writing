#!/bin/bash
# Claude cloud environment «anti-ai-slop-writing»: VM setup before the session; pinned Node 24.22.0 (sha256) + npm ci warm-up; pasted by the owner.
# Always exit 0 so diagnostics remain available; sessions must source env.sh and check status.
set -uo pipefail

REPO="${REPO:-/home/user/anti-ai-slop-writing}"
BOOT="$HOME/.anti-ai-slop-writing-bootstrap"
NODE_VERSION="24.22.0"
NODE_ARCH_TAG="linux-x64"
# Pinned tarball and checksum follow the accepted garmin bootstrap (docs/cloud/README.md).
NODE_SHA256="28ea0a438de9a13bd7891fd758eee6c7819ee8af5442dfd8d45bd65e56d4228c"
NODE_URL="https://nodejs.org/dist/v$NODE_VERSION/node-v$NODE_VERSION-$NODE_ARCH_TAG.tar.gz"
NODE_DIR="$BOOT/node-v$NODE_VERSION-$NODE_ARCH_TAG"

BLOCKERS=()
log() { echo "setup: $*"; }
block() { BLOCKERS+=("$1"); echo "WARN: $1" >&2; log "BLOCKED: $1"; }
sha256_of() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
node_ok() { [ -x "$NODE_DIR/bin/node" ] && [ "$("$NODE_DIR/bin/node" --version 2>/dev/null)" = "v$NODE_VERSION" ]; }

# Hook failure blocks acceptance while keeping setup best-effort (agent-kit docs/cloud/README.md).
if [ -d "$REPO/.git" ] && [ -f "$REPO/tools/hooks-install.sh" ] && (cd "$REPO" && bash tools/hooks-install.sh >/dev/null 2>&1); then
  log "kit hooks installed"
else
  block "kit hooks not installed ($REPO: .git or tools/hooks-install.sh missing, or hooks-install failed)"
fi

mkdir -p "$BOOT/bin" || { echo "WARN: cannot create $BOOT" >&2; exit 0; }

# Keep the pinned runtime isolated and leave collisions untouched (docs/cloud/README.md).
if node_ok; then
  log "node v$NODE_VERSION already present at $NODE_DIR (no download)"
elif [ -e "$NODE_DIR" ]; then
  block "$NODE_DIR exists but is not node v$NODE_VERSION — left untouched (collision)"
elif [ "$(uname -s)-$(uname -m)" != "Linux-x86_64" ]; then
  block "pinned tarball is $NODE_ARCH_TAG; host is $(uname -s)-$(uname -m) — Node $NODE_VERSION not installed"
else
  TMP="$(mktemp -d)"
  TARBALL="$TMP/node.tar.gz"
  if ! curl --proto '=https' --proto-redir '=https' -fsSL --retry 2 --max-time 120 -o "$TARBALL" "$NODE_URL"; then
    block "download failed: $NODE_URL (Limited network?) — Node $NODE_VERSION not installed"
  elif [ "$(sha256_of "$TARBALL")" != "$NODE_SHA256" ]; then
    block "sha256 mismatch for $NODE_URL (expected $NODE_SHA256) — tarball discarded, Node not installed"
  else
    STAGE="$NODE_DIR.tmp.$$"
    rm -rf "$STAGE"
    if mkdir -p "$STAGE" && tar -xzf "$TARBALL" -C "$STAGE" --strip-components=1 && mv "$STAGE" "$NODE_DIR" && node_ok; then
      log "node v$NODE_VERSION installed to $NODE_DIR (sha256 verified)"
    else
      rm -rf "$STAGE" "$NODE_DIR"
      block "unpack or self-check failed for the Node tarball — Node not installed"
    fi
  fi
  rm -rf "$TMP"
fi

# A successful exit is diagnostic only; activate runtimes only for an OK verdict (docs/cloud/README.md).
STATUS="OK"
[ "${#BLOCKERS[@]}" -eq 0 ] || STATUS="BLOCKED: $(printf '%s; ' "${BLOCKERS[@]}")"
{
  echo "# Generated by docs/cloud/claude-setup.sh. Source it in the task shell, then re-check:"
  echo "#   node --version == v$NODE_VERSION; stop if ANTI_AI_SLOP_WRITING_BOOT_STATUS != OK."
  printf 'export ANTI_AI_SLOP_WRITING_BOOT_STATUS=%q\n' "$STATUS"
  if [ "$STATUS" = OK ] && node_ok; then
    # shellcheck disable=SC2016  # the literal "$PATH" must expand when env.sh is sourced, not here
    printf 'export PATH=%q:%q:"$PATH"\n' "$BOOT/bin" "$NODE_DIR/bin"
  else
    echo "# runtime NOT activated"
  fi
} > "$BOOT/env.sh.tmp" && mv "$BOOT/env.sh.tmp" "$BOOT/env.sh"
printf '%s\n' "$STATUS" > "$BOOT/status"
if [ "$STATUS" = OK ]; then
  ( . "$BOOT/env.sh" && cd "$REPO" && npm ci --no-audit --no-fund >/dev/null 2>&1) || echo "WARN: npm ci failed (lockfile warm-up)" >&2
fi
log "status: $STATUS"
log "env file: $BOOT/env.sh — setup exit 0 is not an acceptance"
exit 0
